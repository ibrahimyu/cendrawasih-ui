// Generates src/components/icons.ts: the Cendra icon set, drawn from Lucide. Names are Cendra's
// (what the icon means here); values are Lucide's drawings. Add an icon by adding a line below
import { writeFileSync } from 'node:fs';
import { icons } from 'lucide';

const set = {
  // Status
  info: 'Info', success: 'CircleCheck', warning: 'TriangleAlert', danger: 'CircleX',
  // Commerce and sync
  orders: 'ShoppingBag', payments: 'Wallet', receipt: 'Receipt', package: 'Package', truck: 'Truck',
  store: 'Store', building: 'Building2', sync: 'RefreshCw', plug: 'Plug', mapping: 'ArrowLeftRight',
  chart: 'ChartColumn', clock: 'Clock', chat: 'MessageCircle',
  // App
  overview: 'LayoutGrid', alerts: 'Bell', settings: 'SlidersHorizontal', user: 'User', mail: 'Mail',
  calendar: 'Calendar', link: 'Link', help: 'CircleHelp', menu: 'Menu', logout: 'LogOut',
  // Actions
  search: 'Search', add: 'Plus', close: 'X', check: 'Check', edit: 'Pencil', copy: 'Copy',
  delete: 'Trash2', download: 'Download', upload: 'Upload', filter: 'Filter', external: 'ExternalLink',
  show: 'Eye', hide: 'EyeOff',
  // Direction
  'arrow-right': 'ArrowRight', 'chevron-down': 'ChevronDown', 'chevron-right': 'ChevronRight',
};

const entries = Object.entries(set).map(([name, lucide]) => {
  if (!icons[lucide]) throw new Error(`Lucide has no icon named ${lucide}`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(icons[lucide])},`;
});

writeFileSync(new URL('../src/components/icons.ts', import.meta.url), `/* Generated by scripts/build-icons.mjs. Do not edit.
   Drawings from Lucide (https://lucide.dev), ISC License, Copyright (c) Lucide Contributors. */

export type IconNode = readonly (readonly [tag: string, attrs: Readonly<Record<string, string>>])[];

export const ICONS = {
${entries.join('\n')}
} as const satisfies Record<string, IconNode>;
`);
console.log(`icons.ts: ${entries.length} icons`);
