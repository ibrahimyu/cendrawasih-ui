// Compiles the DTCG token files in tokens/ into src/styles/tokens.css and src/styles/tailwind.css.
// Theme-aware colors become light-dark() pairs, so the page follows the OS theme unless an
// ancestor sets data-theme="light" or data-theme="dark".
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const load = (f) => JSON.parse(readFileSync(new URL(`tokens/${f}`, root), 'utf8'));
const brand = load('brand.tokens.json');
const day = load('day.tokens.json');
const night = load('night.tokens.json');

// Walk a token group, yielding [path, token] for every leaf that has a $value
function* leaves(group, path = []) {
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith('$') || typeof node !== 'object') continue;
    if ('$value' in node) yield [[...path, key], node];
    else yield* leaves(node, [...path, key]);
  }
}

// Token path -> CSS custom property name
function varName(path) {
  const [group, ...rest] = path;
  if (group === 'color' && rest[0] === 'brand') return `--${rest[1]}`;
  if (group === 'color' && rest[0] === 'on') return `--on-${rest[1]}`;
  if (group === 'color') return `--${rest.join('-')}`;
  if (group === 'font') return `--font-${rest[1]}`;
  return `--${path.join('-')}`;
}

const alias = (v) => typeof v === 'string' && /^\{.+\}$/.test(v);
const ref = (v) => `var(${varName(v.slice(1, -1).split('.'))})`;
const dim = (d) => `${d.value}${d.value === 0 ? '' : d.unit}`;

function color(v) {
  if (alias(v)) return ref(v);
  if (v.alpha == null || v.alpha === 1) return v.hex;
  const [r, g, b] = v.components.map((c) => Math.round(c * 255));
  return `rgb(${r} ${g} ${b} / ${v.alpha})`;
}

function value(token, type) {
  const v = token.$value;
  if (alias(v)) return ref(v);
  switch (type) {
    case 'color': return color(v);
    case 'dimension': return dim(v);
    case 'shadow': return `${dim(v.offsetX)} ${dim(v.offsetY)} ${dim(v.blur)} ${dim(v.spread)} ${color(v.color)}`;
    case 'duration': return dim(v);
    case 'cubicBezier': return `cubic-bezier(${v.join(', ')})`;
    case 'fontFamily': return v.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ');
    default: return String(v);
  }
}

// $type is inherited from the closest group that declares it
function typeOf(group, path) {
  let type, node = group;
  for (const key of path) {
    if (node.$type) type = node.$type;
    node = node[key];
  }
  return node.$type ?? type;
}

const decls = [];
for (const [path, token] of leaves(brand)) {
  if (path[0] === 'typography') continue;
  decls.push(`  ${varName(path)}: ${value(token, typeOf(brand, path))};`);
}

// Composite corner shapes built from the radius tokens. The feather tip marks things that only
// label (tags, badges, counts); anything you press is a pill
const shapes = [
  ['radius-feather', 'var(--radius-sm) var(--radius-sm) var(--radius-sm) var(--radius-nib)', 'Tags, badges and counts: three round corners and one sharp tip. Never on anything clickable.'],
];
for (const [name, val] of shapes) decls.push(`  --${name}: ${val};`);

// Theme tokens: one light-dark() pair per token, or a plain value when both themes agree
const nightTokens = new Map([...leaves(night)].map(([p, t]) => [p.join('.'), t]));
for (const [path, token] of leaves(day)) {
  const type = typeOf(day, path);
  const other = nightTokens.get(path.join('.'));
  if (!other) throw new Error(`night.tokens.json is missing ${path.join('.')}`);
  const light = value(token, type);
  const dark = value(other, type);
  let pair = light === dark ? light : `light-dark(${light}, ${dark})`;
  if (type === 'shadow' && light !== dark) {
    // Only the color may differ between themes: light-dark() works on colors, not whole shadows
    const geometry = (t) => value({ $value: { ...t.$value, color: { hex: '' } } }, 'shadow');
    if (geometry(token) !== geometry(other)) throw new Error(`${path.join('.')}: shadows may differ only in color`);
    pair = `${geometry(token)}light-dark(${color(token.$value.color)}, ${color(other.$value.color)})`;
  }
  decls.push(`  ${varName(path)}: ${pair};`);
}

const fonts = [
  ['Google Sans', 'google-sans-latin-wght-normal', '400 700'],
  ['Karla', 'karla-latin-400-normal', '400'],
  ['Karla', 'karla-latin-500-normal', '500'],
  ['Karla', 'karla-latin-700-normal', '700'],
].map(([family, file, weight]) =>
  `@font-face {\n  font-family: "${family}";\n  src: url("../fonts/${file}.woff2") format("woff2");\n  font-weight: ${weight};\n  font-style: normal;\n  font-display: swap;\n}`);

const typeStyles = [...leaves(brand.typography)].map(([[name], token]) => {
  const v = token.$value;
  const ext = token.$extensions?.['co.cendra'] ?? {};
  const tracking = ext.letterSpacingEm != null ? `${ext.letterSpacingEm}em` : dim(v.letterSpacing);
  return { name, family: ref(v.fontFamily), size: dim(v.fontSize), lineHeight: v.lineHeight, weight: v.fontWeight, tracking, transform: ext.textTransform };
});

const header = '/* Generated by scripts/build-tokens.mjs from tokens/*.tokens.json. Do not edit. */\n';

const tokensCss = `${header}
${fonts.join('\n')}

@layer cendra.tokens {
  :root {
    color-scheme: light dark;
  ${decls.join('\n  ')}
  }
  [data-theme="light"] { color-scheme: light; }
  [data-theme="dark"] { color-scheme: dark; }
}

@layer cendra.type {
${typeStyles.map((s) => `  .cx-${s.name} { font-family: ${s.family}; font-size: ${s.size}; line-height: ${s.lineHeight}; font-weight: ${s.weight};${s.tracking === '0' ? '' : ` letter-spacing: ${s.tracking};`}${s.transform ? ` text-transform: ${s.transform};` : ''} }`).join('\n')}
}
`;

// Tailwind 4: colors are inlined as var() so they keep switching with the theme. Fonts, radii,
// shadows, easings and type sizes share Tailwind's namespaces, so they are declared with literal values
const colorNames = decls.map((d) => d.trim().split(':')[0]).filter((n) => {
  const p = [...leaves(brand), ...leaves(day)].find(([path]) => varName(path) === n);
  return p && p[0][0] === 'color';
});
const literal = (prefix) => decls.map((d) => d.trim()).filter((d) => d.startsWith(prefix));
const tailwindCss = `${header}/* Use after Tailwind:
     @layer theme, base, cendra, components, utilities;
     @import "tailwindcss";
     @import "@cendra/ui/tailwind.css";                                         */
@import "./index.css";

@custom-variant dark {
  &:where([data-theme="dark"], [data-theme="dark"] *) { @slot; }
  @media (prefers-color-scheme: dark) {
    &:where(:not([data-theme="light"], [data-theme="light"] *)) { @slot; }
  }
}

@theme inline {
${colorNames.map((n) => `  --color-${n.slice(2)}: var(${n});`).join('\n')}
}

@theme {
  --spacing: 4px;
  ${[...literal('--font-'), ...literal('--radius-'), ...literal('--shadow-'), ...literal('--ease-')].join('\n  ')}
${typeStyles.map((s) => [
  `  --text-${s.name}: ${s.size};`,
  `  --text-${s.name}--line-height: ${s.lineHeight};`,
  `  --text-${s.name}--font-weight: ${s.weight};`,
  s.tracking === '0' ? null : `  --text-${s.name}--letter-spacing: ${s.tracking};`,
].filter(Boolean).join('\n')).join('\n')}
}
`;

writeFileSync(new URL('src/styles/tokens.css', root), tokensCss);
writeFileSync(new URL('src/styles/tailwind.css', root), tailwindCss);

// The token reference in docs/design-language.md, between the tokens:start and tokens:end markers
const row = (...cells) => `| ${cells.join(' | ')} |`;
const code = (s) => `\`${s}\``;
const describe = (t) => (t.$description ?? '').replace(/\|/g, '\\|');
const nightOf = (path) => nightTokens.get(path.join('.'));
const shown = (t, type) => value(t, type).replace(/var\(--([a-z0-9-]+)\)/g, '$1');
const colorRows = [
  ...[...leaves(brand.color)].map(([p, t]) => row(code(varName(['color', ...p]).slice(2)), code(shown(t, 'color')), code(shown(t, 'color')), describe(t))),
  ...[...leaves(day.color)].map(([p, t]) => row(code(varName(['color', ...p]).slice(2)), code(shown(t, 'color')), code(shown(nightOf(['color', ...p]), 'color')), describe(t))),
];
const typeRows = typeStyles.map((s) => {
  const t = brand.typography[s.name];
  const family = t.$value.fontFamily.includes('display') ? 'Google Sans' : 'Karla';
  return row(code(`cx-${s.name}`), family, `${s.size} / ${s.lineHeight}`, s.weight, s.tracking, describe(t));
});
const scaleRows = [
  ...['space', 'radius', 'stroke', 'opacity', 'duration', 'ease'].flatMap((g) => [...leaves(brand[g])].map(([p, t]) =>
    row(code(varName([g, ...p]).slice(2)), value(t, typeOf(brand, [g, ...p])), describe(t)))),
  ...shapes.map(([name, val, use]) => row(code(name), code(val.replace(/var\(--([a-z0-9-]+)\)/g, '$1')), use)),
  row(code('shadow-overlay'), 'Day and Night pair', describe(day.shadow.overlay)),
];
const reference = `<!-- tokens:start (generated by scripts/build-tokens.mjs; edit tokens/ instead) -->
## Tokens

The source of truth is \`tokens/\` (W3C design token format). \`npm run tokens\` compiles it to \`src/styles/tokens.css\`, which every product imports, and rewrites this section.

### What each color is for

${row('Token', 'Day', 'Night', 'Use')}
${row('---', '---', '---', '---')}
${colorRows.join('\n')}

### Type scale

Fonts are self-hosted in \`src/fonts/\`: Google Sans (variable, 400 to 700) and Karla (400, 500, 700).

${row('Class', 'Family', 'Size / line height', 'Weight', 'Tracking', 'Use')}
${row('---', '---', '---', '---', '---', '---')}
${typeRows.join('\n')}

### Spacing, radius, shape, stroke, opacity, motion, elevation

${row('Token', 'Value', 'Use')}
${row('---', '---', '---')}
${scaleRows.join('\n')}
<!-- tokens:end -->`;
const docUrl = new URL('docs/design-language.md', root);
const doc = readFileSync(docUrl, 'utf8');
const start = doc.indexOf('<!-- tokens:start');
const end = doc.indexOf('<!-- tokens:end -->');
if (start < 0 || end < 0) throw new Error('docs/design-language.md is missing the tokens:start / tokens:end markers');
writeFileSync(docUrl, doc.slice(0, start) + reference + doc.slice(end + '<!-- tokens:end -->'.length));
console.log(`tokens.css: ${decls.length} variables, ${typeStyles.length} type styles`);
